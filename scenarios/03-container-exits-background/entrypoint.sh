#!/usr/bin/env bash
#
# entrypoint.sh — стартовый скрипт контейнера (это PID 1).
#
# БАГ (намеренный): приложение запускается В ФОНЕ через "&", после чего
# скрипт доходит до конца и ЗАВЕРШАЕТСЯ. А контейнер живёт только пока
# жив его PID 1 (этот скрипт). PID 1 завершился -> контейнер остановился
# с кодом 0, хотя python "как бы запущен".
#
# Правильно — запускать процесс НА ПЕРЕДНЕМ ПЛАНЕ (без "&"), а лучше через
# exec, чтобы приложение стало самим PID 1 и получало сигналы.

echo "entrypoint: подготовка окружения..."
echo "entrypoint: запускаю сервис..."

# --- вот здесь баг: "&" отправляет процесс в фон ---
python3 /app/app.py &

echo "entrypoint: сервис запущен (как мне кажется). Скрипт завершается."
# скрипт доходит сюда и выходит -> PID 1 мёртв -> контейнер останавливается
