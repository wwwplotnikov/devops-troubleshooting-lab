#!/usr/bin/env bash
#
# fix.sh — разбор инцидента 03: диагностика -> причина -> решение -> проверка.
# В конце ждёт клавишу, удаляет контейнер и возвращает лабу в исходное состояние.
#
set -euo pipefail
cd "$(dirname "$0")"
source ../../lib.sh

CONTAINER="incident-03"

banner "РАЗБОР ИНЦИДЕНТА 03"

# ─────────────────────────────────────────────────────────────
step 1 "диагностика" "Статус и код выхода контейнера"
explain "Контейнер не работает. Смотрим статус и, главное, КОД ВЫХОДА:"
echo ""
run_sh "docker ps -a --filter name=${CONTAINER} --format 'table {{.Names}}\t{{.Status}}'"
echo ""
info "Точный код выхода:"
run_sh "docker inspect ${CONTAINER} --format 'ExitCode={{.State.ExitCode}} Error={{.State.Error}}'"
echo ""
explain "Exited (0). Код 0 = процесс завершился УСПЕШНО, без ошибки."
explain "Это ключевая улика: проблема НЕ в том, что приложение упало с ошибкой."

# ─────────────────────────────────────────────────────────────
step 2 "диагностика" "Логи — есть ли ошибка? (спойлер: нет)"
explain "Обычно docker logs показывает причину падения. Но здесь:"
echo ""
run docker logs "$CONTAINER"
echo ""
explain "Ошибки нет. Скрипт отработал, написал 'сервис запущен... скрипт завершается'"
explain "и вышел. Всё 'успешно' — но контейнер мёртв. Почему?"

# ─────────────────────────────────────────────────────────────
step 3 "причина" "Контейнер жив, пока жив его PID 1"
explain "Главное правило контейнеров: контейнер работает ровно столько, сколько"
explain "работает его ГЛАВНЫЙ процесс (PID 1). Как только PID 1 завершается —"
explain "контейнер останавливается, с тем кодом, что вернул PID 1."
echo ""
info "Посмотрим, как запускается процесс — заглянем в entrypoint.sh:"
run_sh "grep -nE 'python3|&|exec' entrypoint.sh || true"
echo ""
explain "Вот баг: 'python3 /app/app.py &' — символ '&' запускает приложение В ФОНЕ."
explain "Скрипт (PID 1) не ждёт его, доходит до конца и завершается с кодом 0."
explain "PID 1 вышел -> контейнер остановился. Приложение в фоне убили вместе с ним."
explain ""
explain "То есть само приложение исправно — неверен способ запуска: фоном вместо"
explain "переднего плана."

# ─────────────────────────────────────────────────────────────
step 4 "решение" "Запускаем процесс на переднем плане через exec"
explain "Процесс должен работать на ПЕРЕДНЕМ ПЛАНЕ и стать PID 1."
explain "Лучший способ — exec: он ЗАМЕНЯЕТ процесс скрипта процессом python,"
explain "и python становится самим PID 1 (и корректно получает сигналы, напр. SIGTERM)."
echo ""
info "Меняем 'python3 /app/app.py &' на 'exec python3 /app/app.py' в entrypoint.sh:"
run sed -i 's|^python3 /app/app.py &|exec python3 /app/app.py|' entrypoint.sh
echo ""
info "Теперь строка запуска в entrypoint.sh:"
run_sh "grep -nE 'python3' entrypoint.sh"
echo ""
info "Пересобираем образ и поднимаем заново (баг был в образе -> пересборка):"
run_sh "docker compose up -d --build >/dev/null 2>&1 && echo 'контейнер пересобран и запущен'"
sleep 4

# ─────────────────────────────────────────────────────────────
step 5 "проверка" "Контейнер должен работать стабильно (Up)"
echo ""
run_sh "docker ps --filter name=${CONTAINER} --format 'table {{.Names}}\t{{.Status}}'"
echo ""
info "И логи — приложение должно жить и писать heartbeat:"
run docker logs --tail 4 "$CONTAINER"
echo ""
success "Контейнер работает стабильно (Up) — инцидент решён!"
echo ""
explain "Вывод: exit 0 в контексте контейнера НЕ значит 'всё хорошо' — значит"
explain "'главный процесс завершился'. Причина была в запуске приложения в фоне ('&'):"
explain "PID 1 сразу выходил. Фикс — запуск на переднем плане через exec."

# ─────────────────────────────────────────────────────────────
pause_key "Нажми любую клавишу, чтобы удалить контейнер и вернуть лабу в исходное состояние..."
echo ""
info "Убираю за собой..."
docker compose down >/dev/null 2>&1
success "Контейнер удалён."

info "Возвращаю entrypoint.sh в исходное 'сломанное' состояние (exec -> фоновый '&')..."
sed -i 's|^exec python3 /app/app.py|python3 /app/app.py \&|' entrypoint.sh
success "Лаба сброшена — готова к повторному запуску. Чисто."
echo ""
