#!/usr/bin/env bash
#
# fix.sh — пошаговый разбор: диагностика -> причина -> решение -> проверка.
# В конце ждёт нажатия клавиши и удаляет контейнер.
#
set -euo pipefail
cd "$(dirname "$0")"
source ../../lib.sh

CONTAINER="incident-01"

banner "РАЗБОР ИНЦИДЕНТА 01"

# Проверим, что контейнер поднят (иначе просим запустить start.sh)
if ! docker ps --format '{{.Names}}' | grep -q "^${CONTAINER}$"; then
    symptom "Контейнер ${CONTAINER} не запущен. Сначала выполни ./start.sh"
    exit 1
fi

# ─────────────────────────────────────────────────────────────
step 1 "диагностика" "На каком адресе слушает приложение ВНУТРИ контейнера?"
explain "Снаружи refused. Значит нужно понять, слушает ли вообще кто-то 8080"
explain "внутри контейнера, и — главное — на каком интерфейсе."
echo ""
run docker exec "$CONTAINER" ss -tlnp
echo ""
explain "Видим строку вида:  LISTEN  127.0.0.1:8080"
explain "Приложение слушает 127.0.0.1 — это loopback ВНУТРИ контейнера."

# ─────────────────────────────────────────────────────────────
step 2 "причина" "Почему бинд на 127.0.0.1 ломает проброс?"
explain "У контейнера свой network namespace со своими интерфейсами:"
explain "  • lo   (127.0.0.1) — внутренний loopback контейнера"
explain "  • eth0 (172.x.x.x) — интерфейс контейнера в bridge-сети Docker"
explain ""
explain "Проброс -p доставляет пакет (через iptables DNAT) на eth0 контейнера."
explain "Но приложение слушает только на lo (127.0.0.1) и пакеты с eth0 НЕ видит."
explain "Итог: пакет пришёл на eth0:8080, там никто не слушает -> refused."
explain ""
explain "Правильно — слушать на 0.0.0.0 (все интерфейсы контейнера, включая eth0)."

# ─────────────────────────────────────────────────────────────
step 3 "причина №2 / решение" "Баг запечён в образ — правильный фикс это пересборка"
explain "Важно: адрес бинда зашит в app.py, который СКОПИРОВАН в образ при сборке."
explain "Значит это дефект ОБРАЗА, а не временный сбой рантайма."
explain ""
explain "Можно было бы поправить sed-ом внутри живого контейнера, НО:"
explain "  • процесс python — это PID 1 контейнера;"
explain "  • убить PID 1 = остановить весь контейнер (контейнер жив, пока жив PID 1);"
explain "  • а sed по файлу не влияет на уже запущенный процесс в памяти."
explain "Поэтому правка 'на живую' тут костыльна и ломает контейнер."
explain ""
explain "Правильно для дефекта образа — исправить исходник и ПЕРЕСОБРАТЬ образ."
echo ""
info "1) Правим бинд в исходнике app.py (на хосте):"
run sed -i 's/BIND_HOST = "127.0.0.1"/BIND_HOST = "0.0.0.0"/' app.py
echo ""
info "2) Останавливаем сломанный контейнер и пересобираем образ:"
run_sh "docker compose down >/dev/null 2>&1"
run_sh "docker compose up -d --build >/dev/null 2>&1 && echo 'образ пересобран, контейнер поднят'"
sleep 2
echo ""
info "3) Проверяем, что теперь приложение слушает на 0.0.0.0:"
run docker exec "$CONTAINER" ss -tlnp

# ─────────────────────────────────────────────────────────────
step 4 "проверка" "Стучимся снаружи ещё раз"
echo ""
printf "    ${C_GREEN}\\$ curl -sS --max-time 5 http://localhost:8080${C_RESET}\n"
if curl -sS --max-time 5 http://localhost:8080 2>&1 | sed 's/^/    /'; then
    echo ""
    success "Теперь приложение отвечает снаружи — инцидент решён!"
else
    echo ""
    symptom "Что-то пошло не так — проверь вывод выше."
fi

echo ""
explain "Вывод: -p был настроен верно. Причина refused — бинд приложения на"
explain "127.0.0.1 вместо 0.0.0.0. Так как баг зашит в образ, чиним пересборкой,"
explain "а не правкой на живую. Симптом 'refused' (а не timeout) сразу подсказывал:"
explain "пакет доходит, но на порту никто не слушает."

# ─────────────────────────────────────────────────────────────
pause_key "Нажми любую клавишу, чтобы удалить контейнер и вернуть лабу в исходное состояние..."
echo ""
info "Убираю за собой..."
docker compose down >/dev/null 2>&1
success "Контейнер удалён."

# Возвращаем "сломанное" состояние в исходник, чтобы лаба была воспроизводима
# при следующем запуске и репозиторий оставался в исходном (сломанном) виде.
info "Возвращаю исходник app.py в исходное 'сломанное' состояние (0.0.0.0 -> 127.0.0.1)..."
sed -i 's/BIND_HOST = "0.0.0.0"/BIND_HOST = "127.0.0.1"/' app.py
success "Лаба сброшена — готова к повторному запуску. Чисто."
echo ""
