#!/usr/bin/env python3
"""
Приложение, которому для работы нужно ~120 МБ памяти (например, держит
в памяти рабочий набор данных / кэш). Оно НЕ течёт: аллоцирует фиксированный
объём один раз и дальше стабильно работает.

Проблема сценария не в приложении, а в том, что контейнеру задан слишком
маленький лимит памяти (меньше, чем приложению реально нужно), поэтому
ядро убивает процесс OOM-киллером ещё на старте.
"""
import time
import sys

# Сколько памяти приложению реально нужно для работы (примерно 120 МБ).
NEEDED_MB = 120

def main():
    print(f"app: старт, выделяю рабочий набор ~{NEEDED_MB} МБ...", flush=True)

    # Аллоцируем фиксированный объём и удерживаем его (bytearray реально
    # занимает физическую память, не ленивую).
    chunk = bytearray(NEEDED_MB * 1024 * 1024)
    # трогаем страницы, чтобы они точно были заняты в RSS
    for i in range(0, len(chunk), 4096):
        chunk[i] = 1

    print(f"app: рабочий набор {NEEDED_MB} МБ выделен, приложение готово к работе", flush=True)

    while True:
        print("heartbeat: сервис жив", flush=True)
        time.sleep(5)

if __name__ == "__main__":
    main()
