#!/usr/bin/env bash
#
# fix.sh — разбор инцидента 05: диагностика -> причина -> решение -> проверка.
# В конце ждёт клавишу, удаляет контейнер+том и возвращает лабу в исходное состояние.
#
set -euo pipefail
cd "$(dirname "$0")"
source ../../lib.sh

CONTAINER="incident-05"

banner "РАЗБОР ИНЦИДЕНТА 05"

# на всякий случай убедимся, что контейнер поднят (start.sh мог оставить его живым)
if ! docker ps --format '{{.Names}}' | grep -q "^${CONTAINER}$"; then
    docker compose up -d --build >/dev/null 2>&1
    sleep 2
fi

# ─────────────────────────────────────────────────────────────
step 1 "диагностика" "Проверяем, куда смонтирован том"
explain "Данные пропали, хотя volume есть. Сначала посмотрим, куда он смонтирован:"
echo ""
run_sh "docker inspect ${CONTAINER} --format '{{range .Mounts}}{{.Type}} {{.Name}} -> {{.Destination}}{{println}}{{end}}'"
echo ""
explain "Том смонтирован в /data. Значит персистентно только то, что лежит в /data."

# ─────────────────────────────────────────────────────────────
step 2 "диагностика" "Проверяем, куда РЕАЛЬНО пишет приложение"
explain "Запишем тестовую запись и найдём, где физически создался файл данных:"
echo ""
run_sh "docker exec ${CONTAINER} python3 /app/app.py add 'проверочная запись' >/dev/null"
info "Ищем файл data.db внутри контейнера:"
run_sh "docker exec ${CONTAINER} find / -name 'data.db' -not -path '*/proc/*' 2>/dev/null"
echo ""
explain "Файл лежит в /app/data.db, а НЕ в /data."
echo ""
info "Убеждаемся, что в смонтированном томе /data пусто:"
run_sh "docker exec ${CONTAINER} ls -la /data"
echo ""
explain "Том /data пустой. Данные идут мимо него, в /app."

# ─────────────────────────────────────────────────────────────
step 3 "причина" "Относительный путь + WORKDIR = запись мимо тома"
explain "В приложении путь к данным задан ОТНОСИТЕЛЬНЫМ: 'data.db'."
echo ""
run_sh "grep -nE 'DATA_FILE' app.py"
echo ""
explain "Относительный путь считается от рабочей директории процесса, а WORKDIR"
explain "в Dockerfile = /app. Поэтому 'data.db' -> /app/data.db."
explain "Том же смонтирован в /data. Пути не совпадают -> данные пишутся в /app"
explain "(writable-слой контейнера) и умирают вместе с контейнером при пересоздании."
explain ""
explain "Ключевой урок: важно не 'есть ли volume', а совпадает ли путь записи"
explain "приложения с точкой монтирования тома."

# ─────────────────────────────────────────────────────────────
step 4 "решение" "Пишем по абсолютному пути в смонтированный том"
explain "Правильный фикс — приложение должно писать в персистентный том осознанно,"
explain "по абсолютному пути /data/data.db. Правим путь в приложении и пересобираем"
explain "образ (баг зашит в код -> пересборка)."
echo ""
info "Меняем относительный путь на абсолютный /data/data.db:"
run sed -i 's|^DATA_FILE = "data.db"|DATA_FILE = "/data/data.db"|' app.py
echo ""
info "Проверяем строку в app.py:"
run_sh "grep -nE 'DATA_FILE' app.py"
echo ""
info "Пересобираем образ и поднимаем заново (том пока сохраняем):"
run_sh "docker compose up -d --build >/dev/null 2>&1 && echo 'контейнер пересоздан с исправленным путём'"
sleep 2

# ─────────────────────────────────────────────────────────────
step 5 "проверка" "Данные теперь переживают пересоздание контейнера"
explain "Записываем данные, пересоздаём контейнер и проверяем, что они на месте:"
echo ""
run_sh "docker exec ${CONTAINER} python3 /app/app.py add 'важные данные' >/dev/null && echo 'записали: важные данные'"
info "Проверяем, что данные теперь лежат в томе /data:"
run_sh "docker exec ${CONTAINER} ls -la /data"
echo ""
info "Пересоздаём контейнер (down + up):"
run_sh "docker compose down >/dev/null 2>&1 && docker compose up -d >/dev/null 2>&1 && echo 'контейнер пересоздан'"
sleep 2
echo ""
info "Смотрим хранилище после пересоздания:"
run_sh "docker exec ${CONTAINER} python3 /app/app.py list"
echo ""
success "Данные пережили пересоздание контейнера — инцидент решён!"
echo ""
explain "Вывод: volume был настроен верно, но приложение писало мимо него по"
explain "относительному пути. Проверять надо совпадение пути записи и точки"
explain "монтирования, а не просто наличие тома. Фикс — абсолютный путь в том."

# ─────────────────────────────────────────────────────────────
pause_key "Нажми любую клавишу, чтобы удалить контейнер и том и вернуть лабу в исходное состояние..."
echo ""
info "Убираю за собой (удаляю контейнер и том)..."
docker compose down -v >/dev/null 2>&1
success "Контейнер и том удалены."

info "Возвращаю app.py в исходное 'сломанное' состояние (абсолютный -> относительный путь)..."
sed -i 's|^DATA_FILE = "/data/data.db"|DATA_FILE = "data.db"|' app.py
success "Лаба сброшена — готова к повторному запуску. Чисто."
echo ""
